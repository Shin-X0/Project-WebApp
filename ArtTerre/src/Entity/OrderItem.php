<?php

namespace App\Entity;

use App\Repository\OrderItemRepository;
use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;

#[ORM\Entity(repositoryClass: OrderItemRepository::class)]
#[ORM\Table(name: 'order_items')]
class OrderItem
{
    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(options: ['unsigned' => true])]
    private ?int $id = null;

    #[ORM\ManyToOne(inversedBy: 'items')]
    #[ORM\JoinColumn(name: 'order_id', referencedColumnName: 'id', nullable: false, onDelete: 'CASCADE')]
    private ?Order $order = null;

    /* NULL for legacy rows / catalogue placeholder cards —
       matches old order_items.artwork_id. */
    #[ORM\ManyToOne]
    #[ORM\JoinColumn(name: 'artwork_id', referencedColumnName: 'id', nullable: true, onDelete: 'SET NULL')]
    private ?Artwork $artwork = null;

    /* Pins the line to the real seller, so ONLY that seller (or an admin)
       can update the order's status — matches old order_items.artist_id. */
    #[ORM\ManyToOne]
    #[ORM\JoinColumn(name: 'artist_id', referencedColumnName: 'id', nullable: true, onDelete: 'SET NULL')]
    private ?User $artist = null;

    #[ORM\Column(length: 150)]
    private string $title = '';

    /* Title/artist snapshot at purchase time — old `artist` varchar column. */
    #[ORM\Column(name: 'artist', length: 100, nullable: true)]
    private ?string $artistName = null;

    #[ORM\Column(type: Types::DECIMAL, precision: 10, scale: 2)]
    private string $price = '0.00';

    #[ORM\Column(options: ['unsigned' => true, 'default' => 1])]
    private int $qty = 1;

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getOrder(): ?Order
    {
        return $this->order;
    }

    public function setOrder(?Order $order): static
    {
        $this->order = $order;

        return $this;
    }

    public function getArtwork(): ?Artwork
    {
        return $this->artwork;
    }

    public function setArtwork(?Artwork $artwork): static
    {
        $this->artwork = $artwork;

        return $this;
    }

    public function getArtist(): ?User
    {
        return $this->artist;
    }

    public function setArtist(?User $artist): static
    {
        $this->artist = $artist;

        return $this;
    }

    public function getTitle(): string
    {
        return $this->title;
    }

    public function setTitle(string $title): static
    {
        $this->title = $title;

        return $this;
    }

    public function getArtistName(): ?string
    {
        return $this->artistName;
    }

    public function setArtistName(?string $artistName): static
    {
        $this->artistName = $artistName;

        return $this;
    }

    public function getPrice(): string
    {
        return $this->price;
    }

    public function setPrice(string $price): static
    {
        $this->price = $price;

        return $this;
    }

    public function getQty(): int
    {
        return $this->qty;
    }

    public function setQty(int $qty): static
    {
        $this->qty = $qty;

        return $this;
    }
}
